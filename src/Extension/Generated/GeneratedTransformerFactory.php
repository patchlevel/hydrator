<?php

declare(strict_types=1);

namespace Patchlevel\Hydrator\Extension\Generated;

use Patchlevel\Hydrator\Metadata\ClassMetadata;
use Patchlevel\Hydrator\Transformer\CallStack;
use Patchlevel\Hydrator\Transformer\ClassTransformer;
use Patchlevel\Hydrator\Transformer\ClassTransformerFactory;
use Patchlevel\Hydrator\Transformer\TransformerResolver;
use WeakMap;

use function assert;
use function class_exists;
use function is_file;

/**
 * Loads the generated transformer of a class. If there is none, because the class was not warmed up or changed since,
 * null is returned and the class is transformed with reflection. The code is only generated by the
 * {@see GeneratedTransformerWarmer}.
 *
 * @internal registered by the {@see GeneratedTransformerExtension}
 */
final class GeneratedTransformerFactory implements ClassTransformerFactory
{
    /** @var WeakMap<TransformerResolver, CallStack> the generated transformers of a hydrator share their call stack */
    private WeakMap $callStacks;

    public function __construct(
        private readonly TransformerFiles $files,
    ) {
        $this->callStacks = new WeakMap();
    }

    public function create(ClassMetadata $metadata, TransformerResolver $resolver): ClassTransformer|null
    {
        $className = $this->files->className($metadata);
        $fqcn = $this->files->fqcn($className);

        if (!class_exists($fqcn, false)) {
            $file = $this->files->path($className);

            if (!is_file($file)) {
                return null;
            }

            require_once $file;
        }

        $transformer = new $fqcn($metadata, $resolver, $this->callStacks[$resolver] ??= new CallStack());
        assert($transformer instanceof GeneratedTransformer);

        return $transformer;
    }
}
